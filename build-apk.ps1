# Builds the phone-bridge Android APK without Gradle.
#
# Toolchain: JDK 17 (javac/keytool) + Android SDK build-tools (aapt2/d8/zipalign/apksigner).
# Usage:  pwsh -File build-apk.ps1 [-BaseUrl <url>] [-Token <token>]
#
# Passing -BaseUrl bakes that host into the APK so it starts already paired and
# skips the QR setup screen. Omit it for a generic build.

param(
    [string]$BaseUrl = "",
    [string]$Token = ""
)

$ErrorActionPreference = 'Stop'

$JavaHome  = if ($env:PHONE_BRIDGE_JAVA_HOME) { $env:PHONE_BRIDGE_JAVA_HOME } else { 'D:\Java17' }
$SdkRoot   = if ($env:PHONE_BRIDGE_SDK)       { $env:PHONE_BRIDGE_SDK }       else { "$env:LOCALAPPDATA\Android\Sdk" }
$BuildTools = if ($env:PHONE_BRIDGE_BUILD_TOOLS) { $env:PHONE_BRIDGE_BUILD_TOOLS } else { '36.0.0' }

$Root      = $PSScriptRoot
$Project   = "$Root\apk"
$Dist      = "$Root\apk-out"
$ZxingJar  = "$Root\bin\zxing-core-3.5.3.jar"

# aapt2 cannot open paths containing non-ASCII characters under this code page,
# so the whole build is staged under an ASCII scratch directory and the signed
# APK is copied back into the workspace at the end.
$Stage = if ($env:PHONE_BRIDGE_STAGE) { $env:PHONE_BRIDGE_STAGE } else { "$env:TEMP\phone-bridge-build" }
$Src       = "$Stage\src"
$Res       = "$Stage\res"
$Assets    = "$Stage\assets"
$Manifest  = "$Stage\AndroidManifest.xml"
$Out       = "$Stage\build"

$BtDir     = "$SdkRoot\build-tools\$BuildTools"
$Aapt2     = "$BtDir\aapt2.exe"
$D8        = "$BtDir\d8.bat"
$ZipAlign  = "$BtDir\zipalign.exe"
$ApkSigner = "$BtDir\apksigner.bat"
$AndroidJar = Get-ChildItem "$SdkRoot\platforms" -Directory |
    Sort-Object Name -Descending |
    ForEach-Object { "$($_.FullName)\android.jar" } |
    Where-Object { Test-Path $_ } |
    Select-Object -First 1

# d8.bat/apksigner.bat resolve their JVM from JAVA_HOME (falling back to PATH's
# `java`), while javac/keytool here are invoked by absolute path. Pin JAVA_HOME to
# the chosen JDK so every tool in the pipeline runs on the same JVM.
$env:JAVA_HOME = $JavaHome

$Javac     = "$JavaHome\bin\javac.exe"
$Keytool   = "$JavaHome\bin\keytool.exe"

foreach ($tool in @($Aapt2, $D8, $ZipAlign, $ApkSigner, $Javac, $Keytool, $AndroidJar, $ZxingJar)) {
    if (-not (Test-Path $tool)) { throw "missing tool: $tool" }
}

Write-Host "== phone-bridge APK build ==" -ForegroundColor Cyan
Write-Host "jdk        : $JavaHome"
Write-Host "buildTools : $BtDir"
Write-Host "android.jar: $AndroidJar"

if (Test-Path $Stage) { Remove-Item $Stage -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Stage, $Out, "$Out\compiled", "$Out\classes", "$Out\dex", $Dist | Out-Null
Copy-Item "$Project\src"    $Src    -Recurse -Force
Copy-Item "$Project\res"    $Res    -Recurse -Force
Copy-Item "$Project\AndroidManifest.xml" $Manifest -Force
if (-not (Test-Path "$Project\assets")) { New-Item -ItemType Directory -Force -Path "$Project\assets" | Out-Null }
Copy-Item "$Project\assets" $Assets -Recurse -Force

# Whitelist the concrete host for cleartext traffic. The committed resource only
# covers loopback, so the real address is injected here and never checked in.
#
# This MUST run before `aapt2 compile --dir $Res`: that step snapshots the whole
# resource tree, so a file rewritten afterwards never reaches the APK. It used to
# sit next to the BuildDefaults rewrite further down, which compiled the stale
# loopback-only config and left the app unable to reach a 100.x host over HTTP.
if ($baseUrl) {
    $nscHost = ''
    try { $nscHost = ([Uri]$baseUrl).Host } catch { $nscHost = '' }
    if ($nscHost -and $nscHost -notmatch '^(127\.|localhost|10\.0\.2\.2$)') {
        $nscFile = "$Res\xml\network_security_config.xml"
        $nsc = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build-apk.ps1 for host $nscHost - do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">$nscHost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">10.0.2.2</domain>
    </domain-config>
</network-security-config>
"@
        [System.IO.File]::WriteAllText($nscFile, $nsc, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host "  cleartext  : $nscHost" -ForegroundColor DarkGray
    }
}

# 1) compile resources -------------------------------------------------------
Write-Host "`n[1/7] aapt2 compile" -ForegroundColor Cyan
& $Aapt2 compile --dir $Res -o "$Out\compiled\res.zip"
if ($LASTEXITCODE -ne 0) { throw "aapt2 compile failed" }

# 2) link resources + generate R.java ---------------------------------------
Write-Host "[2/7] aapt2 link" -ForegroundColor Cyan
& $Aapt2 link `
    -o "$Out\base.apk" `
    -I $AndroidJar `
    --manifest $Manifest `
    -R "$Out\compiled\res.zip" `
    -A $Assets `
    --java "$Out\gen" `
    --min-sdk-version 24 `
    --target-sdk-version 34 `
    --version-code 1 `
    --version-name 1.0 `
    --auto-add-overlay
if ($LASTEXITCODE -ne 0) { throw "aapt2 link failed" }

# 3) compile java ------------------------------------------------------------
Write-Host "[3/7] javac" -ForegroundColor Cyan

# Bake the host address straight into the APK so the app launches pre-paired.
# Override with -BaseUrl / -Token, or set PHONE_BRIDGE_BASE / PHONE_BRIDGE_TOKEN.
# Passing an empty value keeps the generic build that pairs by QR code.
$baseUrl = if ($BaseUrl) { $BaseUrl } elseif ($env:PHONE_BRIDGE_BASE) { $env:PHONE_BRIDGE_BASE } else { "" }
$bakeToken = if ($Token) { $Token } elseif ($env:PHONE_BRIDGE_TOKEN) { $env:PHONE_BRIDGE_TOKEN } else { "" }
$defaultsFile = "$Src\com\dsh\phonebridge\BuildDefaults.java"
$defaults = @"
package com.dsh.phonebridge;

/**
 * Generated by build-apk.ps1 - do not edit by hand.
 *
 * <p>Empty values produce an unpaired build that pairs by scanning the QR code
 * shown in DSH Settings.
 */
final class BuildDefaults {

    static final String BASE_URL = "$baseUrl";

    static final String TOKEN = "$bakeToken";

    private BuildDefaults() {
    }
}
"@
[System.IO.File]::WriteAllText($defaultsFile, $defaults, (New-Object System.Text.UTF8Encoding($false)))
if ($baseUrl) {
    Write-Host "  baked base : $baseUrl"
    Write-Host "  baked token: $(if ($bakeToken) { $bakeToken.Substring(0, [Math]::Min(8, $bakeToken.Length)) + '...' } else { '(none)' })"
} else {
    Write-Host "  no baked pairing; app will show the QR setup screen"
}

# The cleartext whitelist was injected above, before aapt2 compile.
$javaSources = Get-ChildItem $Src -Recurse -Filter *.java | ForEach-Object { $_.FullName }
$rJava = Get-ChildItem "$Out\gen" -Recurse -Filter *.java -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName }
& $Javac -encoding UTF-8 -source 17 -target 17 -nowarn `
    -classpath "$AndroidJar;$ZxingJar" `
    -d "$Out\classes" `
    @($javaSources + $rJava)
if ($LASTEXITCODE -ne 0) { throw "javac failed" }

# 4) dex ---------------------------------------------------------------------
Write-Host "[4/7] d8" -ForegroundColor Cyan
$classFiles = Get-ChildItem "$Out\classes" -Recurse -Filter *.class | ForEach-Object { $_.FullName }
if (-not $classFiles) { throw "no class files produced" }
& $D8 --release --min-api 24 --lib $AndroidJar --output "$Out\dex" @classFiles $ZxingJar
if ($LASTEXITCODE -ne 0) { throw "d8 failed" }

# 5) package -----------------------------------------------------------------
Write-Host "[5/7] package dex into apk" -ForegroundColor Cyan
$unsigned = "$Out\unsigned.apk"
Copy-Item "$Out\base.apk" $unsigned -Force
Add-Type -AssemblyName System.IO.Compression.FileSystem
Add-Type -AssemblyName System.IO.Compression
$zip = [System.IO.Compression.ZipFile]::Open($unsigned, [System.IO.Compression.ZipArchiveMode]::Update)
try {
    Get-ChildItem "$Out\dex" -Filter *.dex | ForEach-Object {
        $entry = $zip.CreateEntry($_.Name, [System.IO.Compression.CompressionLevel]::Optimal)
        $stream = $entry.Open()
        try {
            $bytes = [System.IO.File]::ReadAllBytes($_.FullName)
            $stream.Write($bytes, 0, $bytes.Length)
        } finally { $stream.Dispose() }
        Write-Host "  + $($_.Name) ($([math]::Round($_.Length/1KB)) KB)"
    }
} finally { $zip.Dispose() }

# 6) align -------------------------------------------------------------------
Write-Host "[6/7] zipalign" -ForegroundColor Cyan
$aligned = "$Out\aligned.apk"
& $ZipAlign -f -p 4 $unsigned $aligned
if ($LASTEXITCODE -ne 0) { throw "zipalign failed" }

# 7) sign --------------------------------------------------------------------
Write-Host "[7/7] apksigner" -ForegroundColor Cyan
$KeystoreBackup = "$Root\bin\phone-bridge-debug.keystore"
$Keystore = "$Stage\phone-bridge-debug.keystore"
$StorePass = 'phonebridge'
if (Test-Path $KeystoreBackup) {
    # reuse the stable identity so re-builds upgrade in place on the phone
    Copy-Item $KeystoreBackup $Keystore -Force
} elseif (-not (Test-Path $Keystore)) {
    Write-Host "  generating keystore"
    & $Keytool -genkeypair -v `
        -keystore $Keystore `
        -alias phonebridge `
        -keyalg RSA -keysize 2048 -validity 10950 `
        -storepass $StorePass -keypass $StorePass `
        -dname "CN=Phone Bridge, OU=DSH, O=DSH, L=, ST=, C=CN"
    if ($LASTEXITCODE -ne 0) { throw "keytool failed" }
}
if (-not (Test-Path $KeystoreBackup)) { Copy-Item $Keystore $KeystoreBackup -Force }
$final = "$Dist\phone-bridge.apk"
& $ApkSigner sign `
    --ks $Keystore `
    --ks-key-alias phonebridge `
    --ks-pass "pass:$StorePass" `
    --key-pass "pass:$StorePass" `
    --v1-signing-enabled true `
    --v2-signing-enabled true `
    --out $final `
    $aligned
if ($LASTEXITCODE -ne 0) { throw "apksigner failed" }

Write-Host "`n== verifying ==" -ForegroundColor Cyan
& $ApkSigner verify --print-certs $final | Select-Object -First 4

$size = [math]::Round((Get-Item $final).Length / 1MB, 2)
Write-Host "`nAPK: $final  ($size MB)" -ForegroundColor Green
